    def args(self, **kwargs):
        result = {
            "workspace_id": self.service.workspace.id,
            "request_id": str(uuid4()),
        }
        result.update(kwargs)
        return result

    async def call(self, name, arguments):
        result = await self.service.call_tool(name, arguments)
        # During the 4b -> 4c transition an old checkout does not advertise
        # authoring outputs yet.  Once the slice is implemented, validate all
        # returned envelopes against the packaged closed schemas.
        validator = OUTPUTS.get(name)
        if validator is not None:
            validator.validate(result)
        return result

    async def create(self, name="slice"):
        result = await self.call("document_create", self.args(name=name, units="mm"))
        self.assertTrue(result["ok"], result)
        self.assertEqual(result["revision"], 0)
        self.assertEqual(result["data"], {
            "name": name,
            "units": "mm",
            "source": None,
            "counts": {"layers": 0, "parts": 0, "primitives": 0, "mops": 0},
        })
        self.assertIn("UNITS_ASSUMED", {item["code"] for item in result["diagnostics"]})
        return result["document"]

    async def inspect(self, handle, *, revision=None, limit=100):
        arguments = {
            "workspace_id": self.service.workspace.id,
            "document": handle,
            "limit": limit,
        }
        if revision is not None:
            arguments["expected_revision"] = revision
        result = await self.call("document_inspect", arguments)
        self.assertTrue(result["ok"], result)
        self.assertIsNone(result["request_id"])
        self.assertEqual(result["revision"], revision if revision is not None else result["revision"])
        return result

    async def inspect_records(self, handle, revision=None):
        result = await self.inspect(handle, revision=revision)
        self.assertIsNone(result["data"]["next_offset"])
        return result["data"]["entities"]

