    @staticmethod
    def assert_cyclic_xyz(testcase, actual, expected, places=9):
        testcase.assertEqual(len(actual), len(expected))
        for offset in range(len(expected)):
            rotated = expected[offset:] + expected[:offset]
            if all(
                all(abs(float(got[index]) - float(want[index])) <= 10 ** -places
                    for index in range(3))
                for got, want in zip(actual, rotated)
            ):
                return
        testcase.fail(f"world corners differ: expected cyclic {expected!r}, got {actual!r}")

